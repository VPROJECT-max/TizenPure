// Build the launcher's icon module from the Lucide SVG subset listed in tools/icons.json.
// Source: launcher/icons/lucide (committed subset, ISC). If ../Assets/icons exists (the full
// Lucide set the project was started from) new names are copied from there first.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const subset = path.join(root, "launcher/icons/lucide");
const full = path.join(root, "../Assets/icons");
const names = JSON.parse(readFileSync(path.join(root, "tools/icons.json"), "utf8"));
const out = {};
for (const name of names) {
  const target = path.join(subset, name + ".svg");
  if (!existsSync(target) && existsSync(path.join(full, name + ".svg"))) copyFileSync(path.join(full, name + ".svg"), target);
  if (!existsSync(target)) throw new Error(`Missing Lucide icon: ${name}`);
  const svg = readFileSync(target, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  out[name] = inner.replace(/\s*\n\s*/g, "").replace(/\s+\/>/g, "/>").trim();
}
const body =
  "// Generated by tools/build-icons.mjs from Lucide (ISC). Do not edit.\n" +
  "export const ICONS: Readonly<Record<string, string>> = " + JSON.stringify(out, null, 1) + ";\n";
writeFileSync(path.join(root, "launcher/src/icons/lucide.ts"), body);
console.log(`Icons: ${names.length} Lucide glyphs, ${Buffer.byteLength(body)} bytes.`);
